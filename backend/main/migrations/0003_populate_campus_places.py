def normalize_name(name):
    return " ".join(name.casefold().replace("№", " ").split())


def populate_places(apps, schema_editor):
    building_model = apps.get_model("main", "Building")
    buildings = building_model.objects.using(schema_editor.connection.alias)
    existing = {normalize_name(building.name): building for building in buildings.order_by("pk")}

    for name, address in PLACES:
        aliases = list(NAME_ALIASES.get(name, ()))
        numbered = re.match(r"^(Корпус|Общежитие) № (\d+)", name)
        if numbered:
            kind, number = numbered.groups()
            aliases.extend((f"{kind} {number}", f"{number} {kind}"))

        building = next(
            (existing[key] for candidate in (name, *aliases)
             if (key := normalize_name(candidate)) in existing),
            None,
        )
        if building is None:
            buildings.create(name=name, address=address)
        elif building.name != name or not building.address:
            building.name = name
            building.address = building.address or address
            building.save(update_fields=["name", "address"])


